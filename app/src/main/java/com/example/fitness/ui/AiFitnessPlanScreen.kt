                        val cs = MaterialTheme.colorScheme
                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .glassEffect(cornerRadius = 20.dp)
                                .padding(16.dp)
                        ) {
                            Column {
                                Row(verticalAlignment = Alignment.CenterVertically) {
                                    Icon(Icons.Default.Psychology, null, tint = cs.primary, modifier = Modifier.size(24.dp))
                                    Spacer(Modifier.width(8.dp))
                                    Text(
                                        "AI 分析與建議",
                                        style = MaterialTheme.typography.titleMedium,
                                        fontWeight = FontWeight.Bold,
                                        color = cs.onSurface
                                    )
                                }
                                Spacer(Modifier.height(12.dp))
                                Text(
                                    aiAdvice,
                                    style = MaterialTheme.typography.bodyMedium,
                                    color = cs.onSurfaceVariant,
                                    lineHeight = 22.sp
                                )
                            }
                        }
                    }
                }

                // ── AI 推薦動作列表 ──
                if (hasGenerated && aiExercises.isNotEmpty()) {
                    item(key = "exercises_header") {
                        val cs = MaterialTheme.colorScheme
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Icon(Icons.Default.FitnessCenter, null, tint = cs.primary, modifier = Modifier.size(22.dp))
                            Spacer(Modifier.width(8.dp))
                            Text(
                                "推薦訓練動作",
                                style = MaterialTheme.typography.titleMedium,
                                fontWeight = FontWeight.Bold,
                                color = cs.onSurface
                            )
                            Spacer(Modifier.width(6.dp))
                            Surface(
                                shape = RoundedCornerShape(6.dp),
                                color = cs.primaryContainer
                            ) {
                                Text(
                                    "${aiExercises.size}",
                                    modifier = Modifier.padding(horizontal = 6.dp, vertical = 1.dp),
                                    style = MaterialTheme.typography.labelSmall,
                                    fontWeight = FontWeight.Bold,
                                    color = cs.primary
                                )
                            }
                        }
                    }

                    items(aiExercises, key = { it.name }) { exercise ->
                        AiExerciseCard(exercise = exercise)
                    }

                    // ── 儲存為課表按鈕 ──
                    item(key = "save_btn") {
                        val cs = MaterialTheme.colorScheme
                        Spacer(Modifier.height(4.dp))
                        Button(
                            onClick = {
                                if (aiExercises.isNotEmpty()) {
                                    val planName = aiPlanName.ifBlank { "AI-$selectedGoal" }
                                    val tpl = SimpleWorkoutTemplate(
                                        name = planName,
                                        bodyPart = "ai_plan",
                                        exercises = aiExercises.map { ex ->
                                            SimpleExerciseItem(
                                                name = ex.name,
                                                sets = ex.sets,
                                                weight = ex.weight
                                            )
                                        },
                                        level = TemplateLevel.INTERMEDIATE,
                                        description = "AI 根據 InBody 數據生成的${selectedGoal}計畫"
                                    )
                                    val entries = aiExercises.map { ex ->
                                        ExerciseEntry(name = ex.name, sets = ex.sets, weight = ex.weight)
                                    }
                                    repository.addPlan(
                                        TrainingPlan(name = planName, exercises = entries)
                                    )
                                    scope.launch {
                                        localTemplateRepo.addTemplate(tpl)
                                        isSaved = true
                                        snackbarHostState.showSnackbar("✅ 已儲存為課表「$planName」")
                                    }
                                }
                            },
                            enabled = !isSaved,
                            modifier = Modifier
                                .fillMaxWidth()
                                .heightIn(min = 48.dp),
                            shape = RoundedCornerShape(16.dp),
                            colors = ButtonDefaults.buttonColors(
                                containerColor = cs.primary,
                                contentColor = cs.onPrimary,
                                disabledContainerColor = cs.surfaceVariant.copy(alpha = 0.5f),
                                disabledContentColor = cs.onSurfaceVariant.copy(alpha = 0.5f)
                            )
                        ) {
                            if (isSaved) {
                                Icon(Icons.Default.CheckCircle, null, modifier = Modifier.size(20.dp))
                                Spacer(Modifier.width(8.dp))
                                Text("已儲存課表", fontWeight = FontWeight.Bold)
                            } else {
                                Icon(Icons.Default.Save, null, modifier = Modifier.size(20.dp))
                                Spacer(Modifier.width(8.dp))
                                Text("儲存為課表", fontWeight = FontWeight.Bold)
                            }
                        }
                    }
                }

                // 底部留白
                item { Spacer(Modifier.height(32.dp)) }
            }
        }
    }
}

