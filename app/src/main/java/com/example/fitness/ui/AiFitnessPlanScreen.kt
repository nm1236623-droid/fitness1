// ── 資料模型 ──
data class AiExercise(
    val name: String,
    val sets: Int,
    val reps: Int,
    val weight: Float,
    val tip: String = ""
)

data class AiFitnessPlanResult(
    val planName: String,
    val advice: String,
    val exercises: List<AiExercise>
)

// ── AI 生成邏輯 ──
private suspend fun generateAiFitnessPlan(
    context: Context,
    latestRecord: InBodyRecord?,
    goal: String
): AiFitnessPlanResult {
    val apiKey = BuildConfig.GEMINI_API_KEY
    val model = GenerativeModel(
        modelName = "gemini-2.5-flash",
        apiKey = apiKey,
        generationConfig = com.google.ai.client.generativeai.type.generationConfig {
            responseMimeType = "application/json"
        }
    )

    val inBodyInfo = if (latestRecord != null) {
        buildString {
            append("使用者最新 InBody 數據：\n")
            append("- 體重：${latestRecord.weightKg} kg\n")
            latestRecord.bodyFatPercent?.let { append("- 體脂率：$it %\n") }
            latestRecord.muscleMassKg?.let { append("- 肌肉量：$it kg\n") }
        }
    } else {
        "使用者目前沒有 InBody 數據，請根據一般成年人給出建議。\n"
    }

    // Get all available exercises from the catalog
    val allParts = listOf("chest", "back", "legs", "arms", "shoulders", "abs")
    val availableExercises = allParts.flatMap { part ->
        PartExerciseCatalog.groupsForPart(part).flatMap { (_, exercises) -> exercises }
    }

    val prompt = """
你是一位專業健身教練和運動科學專家。

$inBodyInfo

使用者的訓練目標：$goal

請根據以上資料，提供個人化的健身計畫。

重要：你推薦的動作名稱必須從以下清單中選擇（完全一致）：
${availableExercises.joinToString("、")}

請回傳以下格式的 JSON：
{
    "planName": "計畫名稱（簡短，如：增肌減脂計畫）",
    "advice": "根據 InBody 數據的分析和建議（150-250字，包含身體狀況分析、飲食建議、訓練頻率建議）",
    "exercises": [
        {
            "name": "動作名稱（必須從上面清單選）",
            "sets": 4,
            "reps": 12,
            "weight": 20.0,
            "tip": "該動作的訓練要點（一句話）"
        }
    ]
}

要求：
1. 推薦 6-10 個動作，涵蓋多個部位
2. 組數 3-5 組，次數 8-15 下
3. 重量根據使用者體重合理推薦（若無數據用一般值）
4. 若目標偏增肌：重量較高、次數較低（8-10）
5. 若目標偏減脂：重量較低、次數較高（12-15）
6. 每個動作給出簡短訓練要點
    """.trimIndent()

    val response = model.generateContent(prompt)
    val text = response.text ?: throw Exception("AI 回應為空")

    return parseAiResponse(text)
}

private fun parseAiResponse(json: String): AiFitnessPlanResult {
    val obj = JSONObject(json)
    val planName = obj.optString("planName", "AI 健身計畫")
    val advice = obj.optString("advice", "")
    val exercisesArray = obj.optJSONArray("exercises") ?: JSONArray()

    val exercises = mutableListOf<AiExercise>()
    for (i in 0 until exercisesArray.length()) {
        val ex = exercisesArray.getJSONObject(i)
        exercises.add(
            AiExercise(
                name = ex.optString("name", ""),
                sets = ex.optInt("sets", 4),
                reps = ex.optInt("reps", 12),
                weight = ex.optDouble("weight", 20.0).toFloat(),
                tip = ex.optString("tip", "")
            )
        )
    }

    return AiFitnessPlanResult(
        planName = planName,
        advice = advice,
        exercises = exercises.filter { it.name.isNotBlank() }
    )
}


