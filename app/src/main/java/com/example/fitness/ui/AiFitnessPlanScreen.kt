/**
 * AI 健身計畫畫面
 * 自動抓取 InBody 數據 → 詢問 AI 增肌減脂建議 → 可儲存為課表
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AiFitnessPlanScreen(
    inBodyRepo: InBodyRepository,
    repository: TrainingPlanRepository,
    onDone: () -> Unit,
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val snackbarHostState = remember { SnackbarHostState() }
    val localTemplateRepo = remember { LocalTemplateRepository(context) }

    // InBody 數據
    val inBodyRecords by inBodyRepo.records.collectAsState()
    val latestRecord = inBodyRecords.maxByOrNull { it.timestamp }

    // AI 狀態
    var isLoading by remember { mutableStateOf(false) }
    var aiAdvice by remember { mutableStateOf("") }
    var aiExercises by remember { mutableStateOf<List<AiExercise>>(emptyList()) }
    var aiPlanName by remember { mutableStateOf("") }
    var hasGenerated by remember { mutableStateOf(false) }
    var selectedGoal by remember { mutableStateOf("增肌減脂") }
    var isSaved by remember { mutableStateOf(false) }

    val goals = listOf("增肌減脂", "增肌為主", "減脂為主", "維持體態", "提升體能")

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.background),
        contentAlignment = Alignment.TopCenter
    ) {
        Scaffold(
            modifier = Modifier.widthIn(max = 840.dp),
            containerColor = Color.Transparent,
            contentWindowInsets = WindowInsets(0, 0, 0, 0),
            snackbarHost = { SnackbarHost(snackbarHostState) },
            topBar = {
                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .statusBarsPadding()
                        .padding(horizontal = 16.dp, vertical = 8.dp)
                        .glassEffect(cornerRadius = 20.dp)
                        .padding(horizontal = 4.dp, vertical = 4.dp)
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        IconButton(onClick = onDone) {
                            Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "返回", tint = MaterialTheme.colorScheme.primary)
                        }
                        Column(modifier = Modifier.weight(1f).padding(start = 4.dp)) {
                            Text(
                                text = "AI 健身計畫",
                                style = MaterialTheme.typography.titleLarge,
                                fontWeight = FontWeight.ExtraBold,
                                color = MaterialTheme.colorScheme.primary
                            )
                            Text(
                                text = "根據 InBody 數據智慧推薦",
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant
                            )
                        }
                        Icon(
                            Icons.Default.AutoAwesome,
                            contentDescription = null,
                            tint = MaterialTheme.colorScheme.primary,
                            modifier = Modifier.size(28.dp).padding(end = 8.dp)
                        )
                    }
                }
            }
        ) { innerPadding ->
            LazyColumn(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(innerPadding),
                contentPadding = PaddingValues(horizontal = 16.dp, vertical = 12.dp),
                verticalArrangement = Arrangement.spacedBy(14.dp)
            ) {
                // ── InBody 數據卡片 ──
                item(key = "inbody_card") {
                    InBodyDataCard(latestRecord = latestRecord)
                }

                // ── 目標選擇 ──
                item(key = "goal_selection") {
                    val cs = MaterialTheme.colorScheme
                    Box(
                        modifier = Modifier
                            .fillMaxWidth()
                            .glassEffect(cornerRadius = 20.dp)
                            .padding(16.dp)
                    ) {
                        Column {
                            Text(
                                "🎯 訓練目標",
                                style = MaterialTheme.typography.titleMedium,
                                fontWeight = FontWeight.Bold,
                                color = cs.onSurface
                            )
                            Spacer(Modifier.height(12.dp))
                            // Use FlowRow-like wrapping with multiple Rows
                            val chunked = goals.chunked(3)
                            chunked.forEach { rowGoals ->
                                Row(
                                    modifier = Modifier.fillMaxWidth(),
                                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                                ) {
                                    rowGoals.forEach { goal ->
                                        val isSelected = selectedGoal == goal
                                        FilterChip(
                                            selected = isSelected,
                                            onClick = { selectedGoal = goal },
                                            label = {
                                                Text(
                                                    goal,
                                                    fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Medium,
                                                    style = MaterialTheme.typography.bodySmall,
                                                    color = if (isSelected) cs.primary else cs.onSurfaceVariant
                                                )
                                            },
                                            leadingIcon = if (isSelected) {
                                                { Icon(Icons.Default.Check, null, Modifier.size(16.dp), tint = cs.primary) }
                                            } else null,
                                            colors = FilterChipDefaults.filterChipColors(
                                                containerColor = cs.surfaceVariant.copy(alpha = 0.4f),
                                                selectedContainerColor = cs.primaryContainer,
                                                selectedLabelColor = cs.primary,
                                                selectedLeadingIconColor = cs.primary,
                                                labelColor = cs.onSurfaceVariant
                                            ),
                                            border = FilterChipDefaults.filterChipBorder(
                                                enabled = true,
                                                selected = isSelected,
                                                borderColor = cs.outline.copy(alpha = 0.5f),
                                                selectedBorderColor = cs.primary
                                            ),
                                            modifier = Modifier.weight(1f)
                                        )
                                    }
                                    // Fill remaining space if row has fewer items
