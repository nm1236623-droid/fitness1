                                hasGenerated = false
                                isSaved = false
                                try {
                                    val result = generateAiFitnessPlan(
                                        context = context,
                                        latestRecord = latestRecord,
                                        goal = selectedGoal
                                    )
                                    aiAdvice = result.advice
                                    aiExercises = result.exercises
                                    aiPlanName = result.planName
                                    hasGenerated = true
                                } catch (e: Exception) {
                                    snackbarHostState.showSnackbar("AI 生成失敗：${e.message}")
                                } finally {
                                    isLoading = false
                                }
                            }
                        },
                        enabled = !isLoading,
                        modifier = Modifier
                            .fillMaxWidth()
                            .heightIn(min = 48.dp),
                        shape = RoundedCornerShape(16.dp),
                        colors = ButtonDefaults.buttonColors(
                            containerColor = cs.primary,
                            contentColor = cs.onPrimary,
                            disabledContainerColor = cs.primary.copy(alpha = 0.5f)
                        )
                    ) {
                        if (isLoading) {
                            CircularProgressIndicator(
                                modifier = Modifier.size(24.dp),
                                color = cs.onPrimary,
                                strokeWidth = 2.dp
                            )
                            Spacer(Modifier.width(12.dp))
                            Text("AI 分析中…", fontWeight = FontWeight.Bold)
                        } else {
                            Icon(Icons.Default.AutoAwesome, null, modifier = Modifier.size(20.dp))
                            Spacer(Modifier.width(8.dp))
                            Text(
                                if (hasGenerated) "重新生成 AI 計畫" else "生成 AI 健身計畫",
